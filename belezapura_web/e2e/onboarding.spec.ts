import { test, expect } from "@playwright/test";

test("cadastro completo cria salão, serviço e profissional e permite novo login", async ({ page, request }) => {
  test.skip(!process.env.BROWSER_FIXTURE_PATH, "Exige autorização por fixture sintética local.");
  const apiUrl = process.env.E2E_API_URL || "http://127.0.0.1:3051";
  test.skip(!["localhost", "127.0.0.1"].includes(new URL(apiUrl).hostname), "Cadastro sintético permitido somente na API local.");
  const id = Date.now();
  const email = `onboarding-${id}@example.test`;
  const name = `Studio sintético ${id}`;
  const password = "test-password-123";
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/onboarding?planId=studio");
  await page.getByPlaceholder("00.000.000/0000-00").fill(String(id).padStart(14, "0"));
  await page.getByPlaceholder("Ex: Studio Bella Estética").fill(name);
  await page.getByPlaceholder("seu@email.com").fill(email);
  await page.getByPlaceholder("Mínimo 6 caracteres").fill(password);
  await page.getByLabel("Telefone do espaço", { exact: true }).fill("11999990000");
  await page.getByPlaceholder("Rua, Avenida...").fill("Rua sintética");
  await page.getByPlaceholder("123", { exact: true }).fill("42");
  await page.getByPlaceholder("Bairro", { exact: true }).fill("Centro");
  await page.getByPlaceholder("Cidade", { exact: true }).fill("São Paulo");
  await page.getByPlaceholder("SP", { exact: true }).fill("SP");
  await page.getByPlaceholder("@seusalao").fill("@studio_teste");
  const next = () => page.getByRole("button", { name: "Continuar", exact: true }).click();
  await next();
  await next();
  await page.getByPlaceholder("Nome do serviço").fill("Manicure sintética");
  await page.getByPlaceholder("Duração", { exact: true }).fill("1h30");
  await page.getByPlaceholder("Preço", { exact: true }).fill("85,50");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await next();
  await page.getByPlaceholder("Nome completo", { exact: true }).fill("Profissional sintética");
  await page.getByPlaceholder("Especialidade", { exact: true }).fill("Unhas");
  await page.getByPlaceholder("Telefone / WhatsApp").fill("11911112222");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await next();
  await next();
  await page.getByRole("button", { name: "E-mail", exact: true }).click();
  await page.getByPlaceholder("seu@email.com").fill(email);
  await page.getByLabel("Nome do favorecido Pix").fill("FAVORECIDA TESTE");
  await page.getByLabel("Tipo do sinal", { exact: true }).selectOption("fixed");
  await page.getByLabel("Valor do sinal", { exact: true }).fill("30");
  await next();
  await next();
  const created = page.waitForResponse(response => response.url() === `${apiUrl}/api/public/onboarding` && response.request().method() === "POST");
  await page.getByRole("button", { name: "Iniciar teste gratuito", exact: true }).click();
  const response = await created;
  expect(response.status()).toBe(201);
  const data = await response.json();
  await expect(page.getByRole("heading", { name: `${name} está pronto!`, exact: true })).toBeVisible();
  const salon = await request.get(`${apiUrl}/api/public/salons/${data.user.salonSlug}`);
  expect(salon.ok()).toBeTruthy();
  const salonData = await salon.json();
  expect(salonData.services).toEqual(expect.arrayContaining([expect.objectContaining({ name: "Manicure sintética", price: 85.5, duration: 90 })]));
  expect(salonData.address).toMatchObject({ street: "Rua sintética", number: "42", city: "São Paulo", state: "SP" });
  expect(salonData).toMatchObject({ instagram: "studio_teste", pixName: "FAVORECIDA TESTE", depositType: "fixed", depositValue: 30, depositPolicy: "required" });
  expect(salonData.professionals[0].phone).toBeUndefined();
  const details = await request.get(`${apiUrl}/api/salon/details`, { headers: { Authorization: `Bearer ${data.token}` } });
  expect((await details.json()).professionals[0].phone).toBe("11911112222");
  await page.evaluate(() => localStorage.clear());
  await page.goto("/login");
  await page.locator('input[type="email"]').fill(email);
  await page.locator('input[type="password"]').fill(password);
  await page.getByRole("button", { name: /Entrar/ }).click();
  await expect(page).toHaveURL(/\/admin$/);
  const date = new Date();
  date.setDate(date.getDate() + 1);
  if (date.getDay() === 0) date.setDate(date.getDate() + 1);
  const dateString = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
  for (const [policy, expected] of [["required", 30], ["optional", 0], ["none", 0]] as const) {
    if (policy !== "required") {
      await page.goto("/admin");
      await page.getByRole("button", { name: "Configurações", exact: true }).first().click();
      await expect(page.getByLabel("Nome do favorecido Pix")).toHaveValue("FAVORECIDA TESTE");
      await page.getByLabel("Exigir sinal", { exact: true }).selectOption(policy);
      await page.getByRole("button", { name: "Salvar alterações", exact: true }).click();
      await expect(page.getByRole("status")).toHaveText("Configurações salvas.");
      await page.reload();
      await page.getByRole("button", { name: "Configurações", exact: true }).first().click();
      await expect(page.getByLabel("Exigir sinal", { exact: true })).toHaveValue(policy);
    }
    const availability = await request.get(`${apiUrl}/api/public/availability?salonId=${salonData.id}&professionalId=${salonData.professionals[0].id}&serviceId=${salonData.services[0].id}&date=${dateString}`);
    const times = await availability.json();
    expect(times.available.length).toBeGreaterThan(0);
    await page.goto(`/agendar/${data.user.salonSlug}`);
    await page.getByRole("button", { name: "Agendar", exact: true }).first().click();
    await page.getByRole("button", { name: `Escolher data ${dateString}` }).click();
    await page.getByRole("button", { name: times.available[0], exact: true }).click();
    await page.getByRole("button", { name: "Sim, confirmar e agendar" }).click();
    await page.getByPlaceholder("Ex: Amanda Silva").fill("Cliente sintética");
    await page.getByPlaceholder("(11) 99999-9999").fill("11988887777");
    if (policy === "optional") await page.getByRole("checkbox", { name: "Quero pagar o sinal opcional no Pix" }).uncheck();
    const reserved = page.waitForResponse(response => response.url() === `${apiUrl}/api/public/appointments` && response.request().method() === "POST");
    await page.getByRole("button", { name: expected > 0 ? /Gerar PIX do Sinal/ : "Confirmar reserva sem sinal" }).click();
    const result = await reserved;
    expect(result.status()).toBe(201);
    expect((await result.json()).deposit).toBe(expected);
    if (expected > 0) {
      await expect(page.getByRole("button", { name: "Copiar Código PIX Copia e Cola" })).toBeVisible();
      await page.getByRole("button", { name: "Concluir e aguardar conferência do salão" }).click();
    }
    await expect(page.getByRole("heading", { name: "Reserva registrada!" })).toBeVisible();
    if (!expected) await expect(page.getByText("Sem sinal antecipado", { exact: true })).toBeVisible();
  }
  expect(errors).toEqual([]);
});
